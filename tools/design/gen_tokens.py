"""Generate code from the design tokens (DESIGN_SYSTEM.md "Tokens").

Language: Python 3, standard library only (ADR 0002).

Inputs (the single source of truth, committed): design/tokens/
color-base.json, brand-colors.json, themes.json, foundations.json.
Outputs (build products, never committed; DESIGN_SYSTEM.md explains why):
  <out>/smy_tokens.h    C header for the native toolkit (Phase 19)
  <out>/smy_tokens.css  CSS custom properties for documentation previews

Before writing, the foundations are validated: 4 px spacing grid, minimum
text size, line heights, known weights, monotonic scales.

Usage: tools/design/gen_tokens.py <out-dir>
"""

import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import check_contrast  # noqa: E402  (theme resolution)

ROOT = pathlib.Path(__file__).resolve().parents[2]
TOKENS = ROOT / "design" / "tokens"


def ident(*parts):
    return "_".join(re.sub(r"[^A-Za-z0-9]+", "_", str(p)).strip("_").upper() for p in parts)


def css_name(*parts):
    return "-".join(re.sub(r"[^A-Za-z0-9]+", "-", str(p)).strip("-").lower() for p in parts)


def argb(hex_colour):
    return f"0xFF{hex_colour.lstrip('#').upper()}u"


def validate(f):
    errors = []
    for key, px in f["space"].items():
        if key.startswith("$"):
            continue
        if px % 4 != 0 and px != 2:
            errors.append(f"space.{key} = {px}: not on the 4 px grid")
    weights = f["font"]["weight"]
    for name, t in f["type"].items():
        if name.startswith("$"):
            continue
        if t["size"] < f["size"]["text-min"]:
            errors.append(f"type.{name}: size {t['size']} below text-min {f['size']['text-min']}")
        if t["line"] < round(t["size"] * 1.2):
            errors.append(f"type.{name}: line height {t['line']} < 1.2 x size")
        if t["line"] % 2 != 0:
            errors.append(f"type.{name}: line height {t['line']} not even (2 px half-grid)")
        if t["weight"] not in weights:
            errors.append(f"type.{name}: unknown weight {t['weight']}")
    radii = [v for k, v in f["radius"].items() if not k.startswith("$")]
    if radii != sorted(radii):
        errors.append("radius scale is not increasing")
    if f["size"]["touch-target-min"] < 24:
        errors.append("touch-target-min below 24 px (WCAG 2.2 2.5.8)")
    if errors:
        for e in errors:
            print(f"gen_tokens: FAIL {e}", file=sys.stderr)
        raise SystemExit(1)


def header(base, themes, f):
    out = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* Copyright 2026 The SMY-OS Authors */",
        "/* GENERATED by tools/design/gen_tokens.py from design/tokens/ - do not edit. */",
        "",
        "#ifndef SMY_DESIGN_TOKENS_H",
        "#define SMY_DESIGN_TOKENS_H",
        "",
        "/* Colours are 0xAARRGGBB (opaque). Lengths are logical pixels at 1x. */",
        "",
        "/* Base ramps and brand colours */",
    ]
    for name, value in base.items():
        out.append(f"#define SMY_BASE_{ident(name)} {argb(value)}")
    for theme, colours in themes.items():
        out += ["", f"/* Theme: {theme} */"]
        for token, value in colours.items():
            out.append(f"#define SMY_COLOR_{ident(theme, token)} {argb(value)}")
    out += ["", "/* Typography */"]
    for name, w in f["font"]["weight"].items():
        out.append(f"#define SMY_FONT_WEIGHT_{ident(name)} {w}")
    for role, fam in f["font"]["family"].items():
        out.append(f'#define SMY_FONT_FAMILY_{ident(role)} "{fam}"')
    for name, t in f["type"].items():
        if name.startswith("$"):
            continue
        out.append(f"#define SMY_TYPE_{ident(name)}_SIZE {t['size']}")
        out.append(f"#define SMY_TYPE_{ident(name)}_LINE {t['line']}")
        out.append(f"#define SMY_TYPE_{ident(name)}_WEIGHT {f['font']['weight'][t['weight']]}")
        out.append(f"#define SMY_TYPE_{ident(name)}_TRACKING_MILLI_EM ({t['tracking']})")
    for group in ("space", "size", "radius", "border"):
        out += ["", f"/* {group} */"]
        for name, v in f[group].items():
            if not name.startswith("$"):
                out.append(f"#define SMY_{ident(group, name)} {v}")
    out += ["", "/* Elevation (one shadow per level; alpha 0-255) */"]
    for level, e in f["elevation"].items():
        if level.startswith("$"):
            continue
        out.append(f"#define SMY_ELEVATION_{level}_Y {e['y']}")
        out.append(f"#define SMY_ELEVATION_{level}_BLUR {e['blur']}")
        out.append(f"#define SMY_ELEVATION_{level}_ALPHA {round(e['opacity'] * 255)}")
    out += ["", "/* Motion (milliseconds; easing control points in thousandths) */"]
    for name, ms in f["motion"]["duration"].items():
        out.append(f"#define SMY_MOTION_{ident(name)}_MS {ms}")
    for name, pts in f["motion"]["easing"].items():
        for i, p in enumerate(pts):
            out.append(f"#define SMY_EASING_{ident(name)}_P{i} {round(p * 1000)}")
    out += ["", "/* Interaction states (alpha 0-255) */"]
    for name, v in f["state"].items():
        if not name.startswith("$"):
            out.append(f"#define SMY_STATE_{ident(name.replace('-opacity', ''))}_ALPHA {round(v * 255)}")
    out += ["", "/* Display scale factors (percent) */"]
    for v in f["scale"]["factors"]:
        out.append(f"#define SMY_SCALE_{round(v * 100)}_PERCENT {round(v * 100)}")
    out += ["", "#endif /* SMY_DESIGN_TOKENS_H */", ""]
    return "\n".join(out)


def css(base, theme_data, f):
    out = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* GENERATED by tools/design/gen_tokens.py from design/tokens/ - do not edit. */",
        "",
        ":root {",
    ]
    for name, value in base.items():
        out.append(f"  --smy-{css_name(name)}: {value};")
    for role, fam in f["font"]["family"].items():
        out.append(f'  --smy-font-{role}: "{fam}", system-ui, sans-serif;' if role == "ui"
                   else f'  --smy-font-{role}: "{fam}", ui-monospace, monospace;')
    for name, t in f["type"].items():
        if name.startswith("$"):
            continue
        out.append(f"  --smy-type-{name}-size: {t['size']}px;")
        out.append(f"  --smy-type-{name}-line: {t['line']}px;")
        out.append(f"  --smy-type-{name}-weight: {f['font']['weight'][t['weight']]};")
        out.append(f"  --smy-type-{name}-tracking: {t['tracking'] / 1000}em;")
    for group in ("space", "size", "radius", "border"):
        for name, v in f[group].items():
            if not name.startswith("$"):
                out.append(f"  --smy-{css_name(group, name)}: {v}px;")
    for level, e in f["elevation"].items():
        if not level.startswith("$"):
            out.append(f"  --smy-elevation-{level}: 0 {e['y']}px {e['blur']}px {e['spread']}px "
                       f"rgb(0 0 0 / {e['opacity']});")
    for name, ms in f["motion"]["duration"].items():
        out.append(f"  --smy-motion-{name}: {ms}ms;")
    for name, pts in f["motion"]["easing"].items():
        out.append(f"  --smy-easing-{name}: cubic-bezier({', '.join(str(p) for p in pts)});")
    out.append("}")
    selectors = {
        "dark": ':root, [data-theme="dark"]',
        "light": '[data-theme="light"]',
        "high-contrast": '[data-theme="high-contrast"]',
    }
    for theme, colours in theme_data["themes"].items():
        out += ["", selectors.get(theme, f'[data-theme="{theme}"]') + " {"]
        for token, ref in colours["colors"].items():
            out.append(f"  --smy-color-{token}: var(--smy-{css_name(ref)});")
        out.append("}")
    out += ["", "@media (prefers-reduced-motion: reduce) {", "  :root {"]
    for name in f["motion"]["duration"]:
        out.append(f"    --smy-motion-{name}: 0ms;")
    out += ["  }", "}", ""]
    return "\n".join(out)


def main(argv):
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    out_dir = pathlib.Path(argv[0])
    f = json.loads((TOKENS / "foundations.json").read_text())
    validate(f)
    base = check_contrast.load_base()
    themes, theme_data = check_contrast.resolve_themes()
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "smy_tokens.h").write_text(header(base, themes, f))
    (out_dir / "smy_tokens.css").write_text(css(base, theme_data, f))
    print(f"gen_tokens: wrote smy_tokens.h and smy_tokens.css to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
