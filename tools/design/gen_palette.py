"""Generate the base colour ramps: design/tokens/palette-anchors.json ->
design/tokens/color-base.json (committed; --check verifies it is current).

Language: Python 3, standard library only (ADR 0002).

Every hue is a ramp of numbered steps (0 = lightest ... 1000 = darkest).
Anchor steps keep their exact colour. Steps between two anchors are
interpolated linearly in OKLCH (lightness, chroma, hue on the short arc),
then brought into the sRGB gamut by lowering chroma. The generator checks
that lightness falls strictly from step to step.

Usage: tools/design/gen_palette.py [--check]
"""

import json
import math
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import colour  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "design" / "tokens" / "palette-anchors.json"
OUT = ROOT / "design" / "tokens" / "color-base.json"


def ramp(steps, anchors):
    known = sorted((int(k), colour.rgb_to_oklch(colour.hex_to_rgb(v)), v) for k, v in anchors.items())
    if known[0][0] != steps[0] or known[-1][0] != steps[-1]:
        raise SystemExit("gen_palette: each hue needs anchors at the first and last step")
    out = {}
    for s in steps:
        exact = [h for k, _, h in known if k == s]
        if exact:
            out[str(s)] = exact[0].upper()
            continue
        lo = max((k for k in known if k[0] < s), key=lambda k: k[0])
        hi = min((k for k in known if k[0] > s), key=lambda k: k[0])
        t = (s - lo[0]) / (hi[0] - lo[0])
        (l1, c1, h1), (l2, c2, h2) = lo[1], hi[1]
        # Near-grey anchors have an unstable hue; borrow the other one's.
        if c1 < 0.02:
            h1 = h2
        if c2 < 0.02:
            h2 = h1
        dh = (h2 - h1 + math.pi) % (2 * math.pi) - math.pi
        out[str(s)] = colour.rgb_to_hex(colour.oklch_to_rgb(l1 + (l2 - l1) * t, c1 + (c2 - c1) * t,
                                                            h1 + dh * t))
    return out


def generate():
    src = json.loads(SRC.read_text())
    steps = src["steps"]
    result = {
        "$comment": "GENERATED by tools/design/gen_palette.py from palette-anchors.json - do not edit.",
    }
    for hue, anchors in src["hues"].items():
        r = ramp(steps, anchors)
        lightness = [colour.rgb_to_oklab(colour.hex_to_rgb(r[str(s)]))[0] for s in steps]
        for a, b, s in zip(lightness, lightness[1:], steps[1:]):
            if b >= a:
                raise SystemExit(f"gen_palette: {hue}.{s} is not darker than the step before")
        result[hue] = r
    return json.dumps(result, indent=2) + "\n"


def main(argv):
    text = generate()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("gen_palette: design/tokens/color-base.json is out of date", file=sys.stderr)
            return 1
        print("gen_palette: color-base.json up to date")
        return 0
    OUT.write_text(text)
    print(f"gen_palette: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
