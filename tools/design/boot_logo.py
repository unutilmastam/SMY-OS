"""Turn the SVG boot logo into run-length-encoded pixel data for the kernel.

Language: Python 3, standard library only (ADR 0002). Rendering uses
rsvg-convert and ImageMagick's convert (build tools, LICENSES.md).

The kernel has no image decoder; it draws this data straight onto the boot
framebuffer (kernel/drivers/bootfb). The logo is rendered at each requested
size onto the boot background colour, so anti-aliased edges are already
blended and the kernel only copies pixels.

Encoding (decoded by bootfb_blit_rle): a sequence of 4-byte runs
    count (1..255), red, green, blue
covering the image row by row, left to right. Runs may cross row ends.

Usage: tools/design/boot_logo.py <logo.svg> <out.c> <background #RRGGBB> <size>...
"""

import subprocess
import sys


def render_rgb(svg, size, background):
    png = subprocess.run(
        ["rsvg-convert", "-w", str(size), "-h", str(size), "-b", background, svg],
        check=True, capture_output=True).stdout
    raw = subprocess.run(
        ["convert", "png:-", "-alpha", "off", "-depth", "8", "rgb:-"],
        input=png, check=True, capture_output=True).stdout
    if len(raw) != size * size * 3:
        raise SystemExit(f"boot_logo: expected {size * size * 3} bytes, got {len(raw)}")
    return raw


def rle(raw):
    out = bytearray()
    i, n = 0, len(raw) // 3
    while i < n:
        px = raw[3 * i:3 * i + 3]
        run = 1
        while i + run < n and run < 255 and raw[3 * (i + run):3 * (i + run) + 3] == px:
            run += 1
        out += bytes([run]) + px
        i += run
    return bytes(out)


def main(argv):
    if len(argv) < 4:
        print(__doc__, file=sys.stderr)
        return 2
    svg, out_path, background, sizes = argv[0], argv[1], argv[2], [int(s) for s in argv[3:]]
    lines = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* Copyright 2026 The SMY-OS Authors */",
        f"/* Generated by tools/design/boot_logo.py from {svg} - do not edit. */",
        "",
        '#include "drivers/bootfb/boot_logo.h"',
        "",
    ]
    entries = []
    for size in sizes:
        data = rle(render_rgb(svg, size, background))
        name = f"boot_logo_{size}"
        lines.append(f"static const uint8_t {name}[{len(data)}] = {{")
        for k in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[k:k + 16]) + ",")
        lines.append("};")
        lines.append("")
        entries.append(f"    {{.width = {size}, .height = {size}, .rle = {name}, .rle_size = sizeof {name}}},")
    lines.append("const struct boot_logo boot_logos[] = {")
    lines += entries
    lines.append("};")
    lines.append(f"const unsigned boot_logo_count = {len(sizes)};")
    with open(out_path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
